window.renderStageWordSearch = function() {
  const headerEl = document.getElementById("edu-game-header-title");
  const stageEl = document.getElementById("edu-game-stage");
  if (headerEl) headerEl.textContent = "🔤 Caça-Palavras Bíblico";
  if (!stageEl) return;

  let pack = window.WORD_SEARCH_LEVELS[window.EBD_STATE.wordSearchIdx] || window.WORD_SEARCH_LEVELS[0];
  if (window.EBD_STATE.fromLessonGames && window.EBD_STATE.customLessonWordSearch) {
    pack = window.EBD_STATE.customLessonWordSearch;
  }
  const words = pack.words || ["CRIACAO", "LUZ", "TERRA", "EDEN", "ADAO"];
  window.EBD_STATE.wordSearchActiveWords = words;
  window.EBD_STATE.wordSearchFound = [];

  const size = 8;
  const grid = Array.from({ length: size }, () => Array(size).fill(""));
  const placements = {};

  words.forEach((word, idx) => {
    const clean = word.substring(0, size);
    const row = idx % size;
    const startCol = Math.max(0, Math.floor((size - clean.length) / 2));
    placements[clean] = [];
    for (let c = 0; c < clean.length; c++) {
      grid[row][startCol + c] = clean[c];
      placements[clean].push(`${row}-${startCol + c}`);
    }
  });

  const letters = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
  for (let r = 0; r < size; r++) {
    for (let c = 0; c < size; c++) {
      if (!grid[r][c]) grid[r][c] = letters[Math.floor(Math.random() * letters.length)];
    }
  }
  window.EBD_STATE.wsPlacements = placements;

  let cellsHtml = "";
  for (let r = 0; r < size; r++) {
    for (let c = 0; c < size; c++) {
      const cid = `${r}-${c}`;
      cellsHtml += `<button type="button" id="ws-cell-${cid}" onclick="tapStageWSCell('${cid}')" style="height:34px; border-radius:8px; border:1.5px solid #38bdf8; background:#0f172a; color:#ffffff; font-weight:900; font-size:14px; cursor:pointer;">${grid[r][c]}</button>`;
    }
  }

  stageEl.innerHTML = `
    ${window.buildTenPhasesBarHtml(window.WORD_SEARCH_LEVELS, window.EBD_STATE.wordSearchIdx, "selectStageWSPhase")}
    <div class="ebd-glass-card" style="padding:10px;">
      <div style="font-size:14.5px; font-weight:900; color:#fde047; margin-bottom:6px;">${pack.title}</div>
      <div id="ws-words-list" style="display:flex; flex-wrap:wrap; gap:5px; justify-content:center; margin-bottom:8px;"></div>
      <div style="display:grid; grid-template-columns:repeat(8,1fr); gap:4px; margin-bottom:10px;">
        ${cellsHtml}
      </div>
      <button type="button" class="btn-gold" style="width:100%; padding:9px;" onclick="advanceStageWSPhase()">Próximo Caça-Palavras ➔</button>
    </div>
  `;
  window.updateStageWSPills();
};

window.updateStageWSPills = function() {
  const words = window.EBD_STATE.wordSearchActiveWords || [];
  const pillsEl = document.getElementById("ws-words-list");
  if (!pillsEl) return;
  pillsEl.innerHTML = words.map(w => {
    const found = window.EBD_STATE.wordSearchFound.includes(w);
    return `<span style="padding:3px 9px; border-radius:999px; font-size:11.5px; font-weight:800; background:${found ? "#00c853" : "#1e1b4b"}; color:#fff; border:1.5px solid ${found ? "#fff" : "#38bdf8"};">${found ? "✅ " : ""}${w}</span>`;
  }).join("");
};

window.tapStageWSCell = function(cellId) {
  const placements = window.EBD_STATE.wsPlacements || {};
  for (const [word, coords] of Object.entries(placements)) {
    if (coords.includes(cellId) && !window.EBD_STATE.wordSearchFound.includes(word)) {
      window.ebdWinSound();
      window.EBD_STATE.wordSearchFound.push(word);
      coords.forEach(cid => {
        const el = document.getElementById(`ws-cell-${cid}`);
        if (el) {
          el.style.background = "linear-gradient(180deg, #00e676, #00c853)";
          el.style.borderColor = "#ffffff";
        }
      });
      window.updateStageWSPills();
      if (window.EBD_STATE.wordSearchFound.length === Object.keys(placements).length) {
        window.ebdConfetti();
      }
      return;
    }
  }
  window.ebdClick();
};

