window.tapStageChronoCard = function(cardId, cardOrder) {
  const levelObj = window.CHRONOLOGY_LEVELS[window.EBD_STATE.chronologyIdx] || window.CHRONOLOGY_LEVELS[0];
  const expected = window.EBD_STATE.chronologyStep;
  const feedbackEl = document.getElementById("chrono-game-feedback");
  const cardEl = document.getElementById(`chrono-card-${cardId}`);

  if (cardOrder === expected) {
    window.ebdWinSound();
    if (cardEl) {
      cardEl.style.opacity = "0.4";
      cardEl.style.pointerEvents = "none";
      cardEl.style.borderColor = "#00e676";
    }
    const cardObj = levelObj.cards.find(c => c.id === cardId);
    const slotEl = document.getElementById(`chrono-slot-${expected}`);
    if (slotEl && cardObj) {
      slotEl.style.border = "2px solid #00e676";
      slotEl.style.background = "linear-gradient(180deg, rgba(6,95,70,0.9), rgba(4,47,46,0.95))";
      slotEl.innerHTML = `<strong style="color:#fde047; font-size:11px;">${expected}º • ${cardObj.era}</strong><span style="color:#fff; font-size:11px; font-weight:700;">${cardObj.title}</span>`;
    }
    window.EBD_STATE.chronologyStep += 1;
    if (window.EBD_STATE.chronologyStep > 4) {
      if (feedbackEl) feedbackEl.textContent = "🎉 Parabéns! Ordem Cronológica perfeita!";
      window.ebdConfetti();
    } else {
      if (feedbackEl) feedbackEl.textContent = `✅ Isso mesmo! Agora toque no ${window.EBD_STATE.chronologyStep}º acontecimento!`;
    }
  } else {
    window.ebdErrSound();
    if (feedbackEl) feedbackEl.textContent = `💡 Pense na cronologia bíblica: qual veio no ${expected}º lugar?`;
  }
};

window.advanceStageChronoPhase = function() {
  if (window.EBD_STATE.fromLessonGames) {
    window.renderStageChronology();
    return;
  }
  const vip = typeof isVipUnlocked !== "undefined" && isVipUnlocked;
  const maxAllowed = vip ? window.CHRONOLOGY_LEVELS.length : 10;
  const next = window.EBD_STATE.chronologyIdx + 1;
  if (next >= maxAllowed) {
    window.ebdAskSubscribe("Liberar Todas as 20 Fases da Ordem Cronológica!");
    window.EBD_STATE.chronologyIdx = 0;
  } else {
    window.EBD_STATE.chronologyIdx = next;
  }
  window.renderStageChronology();
};

